// Run against the disposable seed demo on localhost:3330. The real workbook is optional and preview-only.
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { readFileSync } = require('node:fs');
const { createRequire } = require('node:module');
const { resolve } = require('node:path');
const { chromium } = require('playwright');
const ExcelJS = createRequire(resolve(__dirname, '../backend/package.json'))('exceljs');
const url = 'http://localhost:3330';
const xlsx = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

async function main() {
  const [demo, face] = process.argv.slice(2);
  assert(demo, 'Pass the leads-demo.xlsx generated by the seed');
  const browser = await chromium.launch({ channel: 'chrome' });
  try {
    const context = await browser.newContext();
    const login = await context.request.post(`${url}/api/auth/login`, {
      headers: { Origin: url },
      data: { email: 'admin.demo@example.test', password: 'InfoPrepaga-Demo-2026!' }
    });
    assert.equal(login.status(), 200);
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    page.on('response', (response) => {
      const path = new URL(response.url()).pathname;
      if (response.status() >= 400 && path.startsWith('/api/crm/leads'))
        console.error(`Leads API: ${response.status()} ${path}`);
    });
    await page.goto(`${url}/leads`);
    async function read(path) {
      const response = await context.request.get(`${url}/api/crm/${path}`);
      assert.equal(response.status(), 200);
      return response.json();
    }
    assert.equal((await read('leads?portfolioClass=ALL&q=Excel%20demo')).total, 0, 'Use a clean seed demo');
    const [seedLead] = (await read('leads?q=contacto01%40example.test')).items;
    assert(seedLead);
    const wizard = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Importar leads desde Excel' }) });
    const button = (name) => wizard.getByRole('button', { name, exact: true });
    async function open() {
      await page.getByRole('button', { name: 'Importar Excel', exact: true }).click();
    }
    async function upload(file, name) {
      await open();
      await wizard.getByRole('combobox', { name: 'Modalidad de importación' }).selectOption('HISTORICAL');
      await wizard.locator('input[type=file]').setInputFiles(file);
      await button('Analizar archivo').click();
      await wizard.getByText(name, { exact: true }).waitFor();
    }
    async function counts(region, expected) {
      const panel = wizard.getByRole('region', { name: region });
      for (const [label, count] of expected) {
        await panel.getByText(label, { exact: true }).locator('..').getByText(String(count), { exact: true }).waitFor();
      }
    }
    async function confirm() {
      await button('Importar registros').click();
      await page.getByRole('button', { name: 'Confirmar y procesar', exact: true }).click();
    }
    const result = 'Resultado acumulado del lote';
    const plan = 'Lo que se va a procesar';
    if (face) {
      const digest = () => createHash('sha256').update(readFileSync(face)).digest('hex');
      const before = digest();
      await upload(face, 'datos FACE.xlsx');
      await wizard.getByText(/Hojas detectadas \(5\)/).waitFor();
      for (const sheet of ['Pagos', 'Analisis'])
        await wizard.getByText(`Hoja excluida: ${sheet}`, { exact: true }).waitFor();
      assert.equal(await wizard.getByText(/filas con contenido.*fuera de la tabla principal/).count(), 4);
      const origins = await wizard.getByText(/apariciones bloqueadas/).allTextContents();
      const impact = origins.map((text) => Number(text.match(/(\d+) apariciones bloqueadas/)[1]));
      assert(impact.length > 0);
      assert.deepEqual(impact, [...impact].sort((a, b) => b - a));
      await button('Continuar a revisión').click();
      await wizard.getByText('1613 filas detectadas', { exact: true }).waitFor();
      await button('Ver resumen').click();
      assert.equal((await read('lead-imports')).find((batch) => batch.fileName === 'datos FACE.xlsx').imported, 0);
      assert.equal((await read('lead-imports')).find((batch) => batch.fileName === 'datos FACE.xlsx').status, 'REVIEW');
      await page.keyboard.press('Escape');
      await wizard.waitFor({ state: 'hidden' });
      assert.equal(digest(), before);
      console.log('PASS FACE: 1.613 candidatas, 5 hojas, 4 avisos con rango; lote en revisión sin confirmar');
    }
    await upload(demo, 'leads-demo.xlsx');
    await wizard.getByRole('combobox', { name: 'Origen PIPA PIPA', exact: true }).click();
    await page.getByRole('option', { name: 'Base demo Excel', exact: true }).click();
    await button('Continuar a revisión').click();
    const exceptionRow = () => wizard.getByRole('row').filter({ hasText: 'Excepción Excel demo' });
    await exceptionRow().waitFor();
    assert.match(await exceptionRow().innerText(), /Requiere corrección/);
    await button('Ver resumen').click();
    await counts(plan, [['Altas previstas', 3], ['Actualizaciones previstas', 1], ['Consolidaciones previstas', 1], ['Quedarán pendientes', 1]]);
    await confirm();
    await counts(result, [['altas', 3], ['actualizaciones', 1], ['consolidaciones', 1], ['excluidas', 0], ['pendientes', 1]]);
    await button('Cerrar').click();
    await open();
    await button('Importaciones recientes').click();
    await wizard.getByRole('button', { name: /leads-demo\.xlsx.*Parcial.*3 altas.*1 pendientes/ }).click();
    await button('Retomar revisión').press('Enter');
    await button('Revisar fila').click();
    const correction = wizard.getByRole('region', { name: 'Revisar fila 7' });
    assert.equal(await correction.getByLabel('Teléfono', { exact: true }).inputValue(), '123');
    await correction.getByLabel('Teléfono', { exact: true }).fill('');
    await button('Guardar y revisar').click();
    await correction.waitFor({ state: 'hidden' });
    await button('Ver resumen').click();
    await confirm();
    await counts(result, [['altas', 4], ['actualizaciones', 1], ['consolidaciones', 1], ['excluidas', 0], ['pendientes', 0]]);
    assert.equal(await wizard.getByText(/filas que requieren revisión hasta/).count(), 0);
    await button('Ver leads del lote').click();
    const table = page.getByRole('region', { name: 'Tabla de leads' });
    const names = ['Alta Excel demo', 'Archivo Excel demo', 'Pendiente Excel demo', 'Excepción Excel demo', 'Contacto demo 01'];
    for (const name of names) await table.getByRole('button', { name, exact: true }).waitFor();
    assert.equal(await table.getByRole('row').count(), 6);
    for (const [name, classification] of [
      ['Alta Excel demo', 'En gestión'], ['Archivo Excel demo', 'Histórico'],
      ['Pendiente Excel demo', 'Pendiente de clasificación'], ['Excepción Excel demo', 'Pendiente de clasificación']
    ]) assert.match(await table.getByRole('row').filter({ hasText: name }).innerText(), new RegExp(classification));
    const completeBatch = (await read('lead-imports')).find((batch) => batch.fileName === 'leads-demo.xlsx' && batch.result.created === 4);
    const batchLeads = (await read(`leads?portfolioClass=ALL&importBatchId=${completeBatch.id}`)).items;
    const updated = batchLeads.find(({ id }) => id === seedLead.id);
    assert.equal(updated.status, seedLead.status);
    assert.equal(updated.assignedToId, seedLead.assignedToId);
    const activityCounts = () => Promise.all(batchLeads.map(async ({ id }) => (await read(`leads/${id}/history`)).total));
    const beforeReplay = await activityCounts();

    await upload(demo, 'leads-demo.xlsx');
    await wizard.getByText('6 filas ya registradas. No se modificaron leads.', { exact: true }).waitFor();
    await counts(result, [['altas', 0], ['actualizaciones', 0], ['consolidaciones', 0], ['ya registradas', 6], ['excluidas', 0], ['pendientes', 0]]);
    assert.equal(await button('Importar registros').count(), 0);
    await button('Cerrar').click();
    assert.deepEqual(await activityCounts(), beforeReplay);
    for (const [name, count] of [['Alta Excel demo', 2], ['Excepción Excel demo', 1], ['Contacto demo 01', 1]]) {
      await table.getByRole('button', { name, exact: true }).click();
      const profile = page.getByRole('dialog');
      try {
        await profile.getByRole('heading', { name, exact: true }).waitFor();
        await profile.getByRole('heading', { name: 'Procedencias de importación' }).waitFor();
      } catch (error) {
        console.error('Encabezados del perfil demo:', await profile.getByRole('heading').allTextContents());
        throw error;
      }
      await profile.locator('article').first().waitFor();
      assert.equal(await profile.locator('article').count(), count);
      if (name === 'Excepción Excel demo') {
        await profile.getByText('Corrección de contacto', { exact: true }).click();
        await profile.getByText('Teléfono original: 123 · Teléfono aplicado: Vacío', { exact: true }).waitFor();
      }
      await profile.getByRole('button', { name: 'Close', exact: true }).click();
      await profile.waitFor({ state: 'hidden' });
    }
    const changed = new ExcelJS.Workbook();
    await changed.xlsx.readFile(demo);
    changed.getWorksheet('PIPA').getCell('C7').value = '124';
    await page.setViewportSize({ width: 390, height: 844 });
    await upload({ name: 'demo-cambio.xlsx', mimeType: xlsx, buffer: Buffer.from(await changed.xlsx.writeBuffer()) }, 'demo-cambio.xlsx');
    await button('Continuar a revisión').click();
    await wizard.getByText('5 ya registradas', { exact: true }).waitFor();
    await exceptionRow().waitFor();
    assert.match(await exceptionRow().innerText(), /Requiere corrección/);
    console.log('PASS demo: parcial, reanudación, 4 altas / 1 actualización / 1 consolidación, 6 registradas, procedencias y origen cambiado');
  } finally {
    await browser.close();
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
